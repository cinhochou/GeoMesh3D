// 名称显示格式化（侧栏与动画步骤/历史标签共用）。
//
// 抽出来的原因：侧栏原本自己实现了一份「末尾数字转下标」的逻辑，
// 若标签侧再写一份，两处显示口径迟早分叉（同一个正六面体在侧栏是
// 「正六面体₁」、在步骤标签里变成「正六面体1」）。

/**
 * 把名称**末尾**的连续数字转成下标：
 *   '正六面体1' → '正六面体₁'，'c12' → 'c₁₂'，'AB' → 'AB'（无变化）。
 *
 * 只转换结尾那段数字（`/(\d+)(?=\D*$)/`），保持与侧栏原有行为完全一致。
 */
export function toSubscriptName(str: string | null | undefined): string {
  if (!str) return ''
  return str.replace(/(\d+)(?=\D*$)/, (m) =>
    m
      .split('')
      .map((d) => '₀₁₂₃₄₅₆₇₈₉'[Number(d)])
      .join(''),
  )
}
